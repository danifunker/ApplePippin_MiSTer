#!/usr/bin/env python3
"""Regenerate tools/rom/data/traps.tsv and lowmem.tsv from a checkout of
Wolfgang Thaller's "multiversal" Mac interface definitions
(https://github.com/autc04/multiversal, MIT licence).

Usage: python3 -I tools/rom/gen_tables.py scratch/third_party/multiversal

Only names and numbers are extracted (no code).  Parsing is a small
line-based reader so that PyYAML is not needed.
"""
import os, re, sys

def main(root):
    defs = os.path.join(root, 'defs')
    traps = {}      # trap word -> name
    lowmem = {}     # address -> name
    for fn in sorted(os.listdir(defs)):
        if not fn.endswith('.yaml'):
            continue
        kind = None; name = None
        for line in open(os.path.join(defs, fn), encoding='utf-8', errors='replace'):
            if line.startswith('- '):
                kind = None; name = None
            m = re.match(r'^(?:- |  )([\w-]+):\s*(\S*)', line)
            if m:
                if m.group(1) in ('function', 'funptr', 'dispatcher', 'lowmem'):
                    kind = m.group(1); name = None
                continue
            m = re.match(r'^    name: (\S+)', line)
            if m and name is None:
                name = m.group(1)
                continue
            m = re.match(r'^    trap: (0x[0-9A-Fa-f]+)', line)
            if m and name and kind in ('function', 'funptr', 'dispatcher'):
                t = int(m.group(1), 16)
                traps.setdefault(t, name)
                continue
            m = re.match(r'^    address: (0x[0-9A-Fa-f]+)', line)
            if m and name and kind == 'lowmem':
                a = int(m.group(1), 16)
                lowmem.setdefault(a, name)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data')
    os.makedirs(out, exist_ok=True)
    hdr = ('# Generated by tools/rom/gen_tables.py from multiversal '
           '(https://github.com/autc04/multiversal, (c) 2019 Wolfgang Thaller, MIT licence)\n')
    with open(os.path.join(out, 'traps.tsv'), 'w') as f:
        f.write(hdr + '# trap\tname\n')
        for t in sorted(traps):
            f.write('%04X\t%s\n' % (t, traps[t]))
    with open(os.path.join(out, 'lowmem.tsv'), 'w') as f:
        f.write(hdr + '# address\tname\n')
        for a in sorted(lowmem):
            f.write('%04X\t%s\n' % (a, lowmem[a]))
    print('traps', len(traps), 'lowmem', len(lowmem))

if __name__ == '__main__':
    main(sys.argv[1])
