"""Compare two Pippin ROMs region by region and, where feasible, function by
function.  Output is a Markdown report."""
import difflib
import hashlib
import os
import re

from . import rom as R
from .analyze import ROMAnalysis
from .m68k import M68KListing
from .ppc import PPCListing

_line_rx = re.compile(r'^([0-9A-F]{8}) ([0-9A-F]{6}) (?:([0-9A-F]{6}) )?(\S.*)$')


def region_key(r, seen):
    if r.get('rsrc') is not None:
        res = r['rsrc']
        part = r['kind'] if r.get('sec') is None else 'sec%d' % r['sec']['index']
        if r['group'] == 'resource entries':
            part = 'entry'
        return ('rsrc', res.type, res.id, res.name, part)
    k = re.sub(r'0x[0-9A-F]+', '', r['name'])
    n = seen.get(k, 0)
    seen[k] = n + 1
    return ('region', k, n)


def ranges(a, b):
    """Coalesced ranges of differing byte offsets between equal-length a and b."""
    out = []
    i = 0
    n = len(a)
    while i < n:
        if a[i] != b[i]:
            j = i
            while j < n and (a[j] != b[j] or (j + 1 < n and a[j + 1] != b[j + 1]) or (j + 2 < n and a[j + 2] != b[j + 2])):
                j += 1
            out.append((i, j))
            i = j
        else:
            i += 1
    return out


def listing_by_off(lines):
    """Map ROM offset -> line, and ordered offsets; also track current label."""
    m = {}
    order = []
    label = {}
    cur = None
    for l in lines:
        if l.endswith(':') and not l.startswith(' '):
            cur = l[:-1]
            continue
        mm = _line_rx.match(l)
        if mm:
            o = int(mm.group(2), 16)
            m[o] = l
            order.append(o)
            label[o] = cur
    return m, order, label


def excerpt(lines_map, order, lo, hi, ctx=2):
    idx = [i for i, o in enumerate(order) if lo <= o < hi]
    if not idx:
        # find nearest instruction containing lo
        idx = [max([i for i, o in enumerate(order) if o <= lo] or [0])]
    a = max(0, idx[0] - ctx)
    b = min(len(order), idx[-1] + ctx + 1)
    return [lines_map[order[i]] for i in range(a, b)]


def func_starts(d, lo, hi):
    """Heuristic PPC function starts: region start and every word after a blr."""
    out = [lo]
    for a in range(lo, hi - 4, 4):
        if d[a:a + 4] == b'\x4e\x80\x00\x20':
            out.append(a + 4)
    return out


def _norm68k(l):
    mm = re.match(r'^([0-9A-F]{8}) ([0-9A-F]{6}) (.{20}) (.*)$', l)
    if not mm:
        return None
    ins = mm.group(4).split(' ; ')[0].strip()
    ins = re.sub(r'L_[0-9A-F]{8}', 'L', ins)
    ins = re.sub(r'\$ffc[0-9a-f]{5}', '$ROM', ins)
    return int(mm.group(2), 16), ins, l


def _numbers_only(a, b):
    return re.sub(r'\$?[0-9a-fx]+', '#', a) == re.sub(r'\$?[0-9a-fx]+', '#', b)


def write_diff(path_a, path_b, out, la, lb):
    da, db = open(path_a, 'rb').read(), open(path_b, 'rb').read()
    A, B = ROMAnalysis(da, la), ROMAnalysis(db, lb)
    L = ['# %s vs %s: ROM comparison' % (la, lb), '',
         'Generated by `tools/rom/run.py --diff` (pippinrom). Offsets are ROM offsets (CPU address = 0xFFC00000 + offset).', '',
         '| | %s | %s |' % (la, lb), '|---|---|---|',
         '| file | `%s` | `%s` |' % (os.path.basename(path_a), os.path.basename(path_b)),
         '| SHA-1 | `%s` | `%s` |' % (hashlib.sha1(da).hexdigest(), hashlib.sha1(db).hexdigest()),
         '| bytes that differ at the same offset | %d | |' % sum(1 for x, y in zip(da, db) if x != y)]
    for off, size, name in R.HEADER_FIELDS:
        va, vb = A.header[name], B.header[name]
        if va != vb:
            L.append('| header %s (+0x%02X) | 0x%0*X | 0x%0*X |' % (name, off, size * 2, va, size * 2, vb))
    L.append('')

    # ------------------------------------------------ region-level matching
    sa, sb = {}, {}
    ka = {region_key(r, sa): r for r in A.regions if r['kind'] != 'padding'}
    kb = {region_key(r, sb): r for r in B.regions if r['kind'] != 'padding'}
    same_place = moved = relinked = 0
    changed = []
    only = []
    shifts = {}
    for k, ra in ka.items():
        rb = kb.get(k)
        if rb is None:
            only.append((la, ra))
            continue
        if ra['sha1'] == rb['sha1']:
            if ra['start'] == rb['start']:
                same_place += 1
            else:
                moved += 1
                sh = rb['start'] - ra['start']
                shifts[sh] = shifts.get(sh, 0) + 1
        elif ra['group'] == 'resource entries' or ra['name'].startswith('ROM resource list header'):
            # entries hold absolute next/data offsets; compare with those fields neutralised
            ea, eb = bytearray(da[ra['start']:ra['end']]), bytearray(db[rb['start']:rb['end']])
            o = 0 if ra['name'].startswith('ROM resource list header') else 8
            ea[o:o + (4 if o == 0 else 8)] = bytes(4 if o == 0 else 8)
            eb[o:o + (4 if o == 0 else 8)] = bytes(4 if o == 0 else 8)
            if ea == eb:
                relinked += 1
            else:
                changed.append((k, ra, rb))
        else:
            changed.append((k, ra, rb))
    for k, rb in kb.items():
        if k not in ka:
            only.append((lb, rb))
    pa = sum(r['end'] - r['start'] for r in A.regions if r['kind'] == 'padding')
    pb = sum(r['end'] - r['start'] for r in B.regions if r['kind'] == 'padding')
    L += ['## Region level', '',
          '- Non-padding regions: %d in %s, %d in %s.' % (len(ka), la, len(kb), lb),
          '- Identical and at the same offset: %d. Identical but moved: %d (shift: %s).' % (
              same_place, moved, ', '.join('%+d bytes x %d' % (s, n) for s, n in sorted(shifts.items(), key=lambda x: -x[1]))),
          '- Resource list header/entries identical except for their absolute link/data offsets: %d.' % relinked,
          '- Changed: %d. Present in only one ROM: %d.' % (len(changed), len(only)),
          '- Padding bytes: %d vs %d.' % (pa, pb), '',
          '| region | %s offset | size | %s offset | size | differing bytes (if same size) |' % (la, lb), '|---|---|---:|---|---:|---:|']
    for k, ra, rb in changed:
        sza, szb = ra['end'] - ra['start'], rb['end'] - rb['start']
        nd = sum(1 for x, y in zip(da[ra['start']:ra['end']], db[rb['start']:rb['end']]) if x != y) if sza == szb else '-'
        L.append('| %s | 0x%06X | %d | 0x%06X | %d | %s |' % (ra['name'].replace('|', '/'), ra['start'], sza, rb['start'], szb, nd))
    for who, r in only:
        L.append('| only in %s: %s | 0x%06X | %d | | | |' % (who, r['name'], r['start'], r['end'] - r['start']))
    L.append('')

    # ------------------------------------------- equal-size changed regions
    L += ['## Byte and function level detail', '']
    for k, ra, rb in changed:
        sza, szb = ra['end'] - ra['start'], rb['end'] - rb['start']
        if ra['name'].startswith('68K main code'):
            continue
        if ra['group'] == 'resource entries' or ra['name'].startswith('ROM resource list header'):
            continue
        a = da[ra['start']:ra['end']]
        b = db[rb['start']:rb['end']]
        L.append('### %s' % ra['name'])
        L.append('')
        if sza != szb:
            L.append('Size differs (%d vs %d); see the per-ROM files %s.' % (sza, szb, ra.get('file')))
            L.append('')
            continue
        rs = ranges(a, b)
        L.append('Differing byte ranges (offsets relative to the region start): ' +
                 ', '.join('+0x%X..+0x%X' % (x, y - 1) for x, y in rs[:40]) + (' ...' if len(rs) > 40 else ''))
        if ra.get('pef') is not None and ra['kind'] == 'header':
            for x, y in rs:
                if 16 + 0x10 <= x < 16 + 0x14:
                    L.append('  (+0x%X is inside the PEF container dateTimeStamp field)' % x)
        L.append('')
        if ra['kind'] == 'codeppc':
            la_ = PPCListing(da, ra['start'], ra['end'], R.ROM_BASE + ra['start'], relcol=ra['start']).lines()
            lb_ = PPCListing(db, rb['start'], rb['end'], R.ROM_BASE + rb['start'], relcol=rb['start']).lines()
            ma, oa, laba = listing_by_off(la_)
            mb, ob, labb = listing_by_off(lb_)
            fstart = func_starts(da, ra['start'], ra['end'])
            groups = {}
            for x, y in rs:
                f = max([o for o in fstart if o <= ra['start'] + x] or [ra['start']])
                g = groups.setdefault(f, [x, y])
                g[0], g[1] = min(g[0], x), max(g[1], y)
            for f, (x, y) in sorted(groups.items()):
                ea = excerpt(ma, oa, ra['start'] + x, ra['start'] + y, ctx=2)
                eb = excerpt(mb, ob, rb['start'] + x, rb['start'] + y, ctx=2)
                n = len([1 for (p, q) in rs if ra['start'] + p >= f and (f, ) and max([o for o in fstart if o <= ra['start'] + p] or [ra['start']]) == f])
                L += ['Function starting at section offset +0x%X (%s; start = instruction after the preceding blr): '
                      '%d differing range(s) in +0x%X..+0x%X' % (f - ra['start'], laba.get(f) or 'unlabelled', n, x, y - 1), '',
                      '```', '; %s' % la] + ea[:60] + ['; %s' % lb] + eb[:60] + ['```', '']
        elif ra['kind'] in ('data', 'table', 'header', 'fcode'):
            for x, y in rs[:12]:
                L.append('- +0x%X: %s -> %s' % (x, a[x:y].hex(), b[x:y].hex()))
            L.append('')

    # ------------------------------------------------------ 68K main code
    ra = next(r for r in A.regions if r['name'].startswith('68K main code'))
    rb = next(r for r in B.regions if r['name'].startswith('68K main code'))
    na = [x for x in (_norm68k(l) for l in M68KListing(da, ra['start'], ra['end'], R.ROM_BASE + ra['start']).lines()) if x]
    nb = [x for x in (_norm68k(l) for l in M68KListing(db, rb['start'], rb['end'], R.ROM_BASE + rb['start']).lines()) if x]
    sm = difflib.SequenceMatcher(None, [x[1] for x in na], [x[1] for x in nb], autojunk=False)
    ops = [o for o in sm.get_opcodes() if o[0] != 'equal']
    refonly = 0
    subst = []
    for tag, i1, i2, j1, j2 in ops:
        if tag == 'replace' and i2 - i1 == j2 - j1 and all(_numbers_only(na[i][1], nb[j][1]) for i, j in zip(range(i1, i2), range(j1, j2))):
            refonly += i2 - i1
            continue
        subst.append((tag, i1, i2, j1, j2))
    # merge hunks closer than 12 instructions
    hunks = []
    for h in subst:
        if hunks and h[1] - hunks[-1][2] < 12 and h[3] - hunks[-1][4] < 12:
            p = hunks[-1]
            hunks[-1] = ('replace', p[1], h[2], p[3], h[4])
        else:
            hunks.append(h)
    def span(n, i1, i2, end):
        a0 = n[i1][0] if i1 < len(n) else end
        a1 = n[i2][0] if i2 < len(n) else end
        return a0, a1

    def shifted_table(h):
        a0, a1 = span(na, h[1], h[2], ra['end'])
        b0, b1 = span(nb, h[3], h[4], rb['end'])
        if a1 - a0 != b1 - b0 or a1 - a0 < 8:
            return False
        xa, xb = da[a0:a1], db[b0:b1]
        for k in range(0, len(xa) - 1, 2):
            wa, wb = (xa[k] << 8) | xa[k + 1], (xb[k] << 8) | xb[k + 1]
            if wa != wb:
                # compare as 32-bit words aligned at k-2 or k
                ok = False
                for q in (k - 2, k):
                    if 0 <= q and q + 4 <= len(xa):
                        la32 = int.from_bytes(xa[q:q + 4], 'big')
                        lb32 = int.from_bytes(xb[q:q + 4], 'big')
                        if abs(la32 - lb32) <= 0x400:
                            ok = True
                if abs(wa - wb) <= 0x400 or ok:
                    continue
                return False
        return True

    tables, rest = [], []
    i = 0
    while i < len(hunks):
        best = None
        for j in range(len(hunks) - 1, i - 1, -1):
            m = ('replace', hunks[i][1], hunks[j][2], hunks[i][3], hunks[j][4])
            if shifted_table(m):
                best = (j, m)
                break
        if best:
            tables.append(best[1])
            i = best[0] + 1
        else:
            rest.append(hunks[i])
            i += 1
    hunks = rest
    L += ['## 68K main code (%d vs %d bytes)' % (ra['end'] - ra['start'], rb['end'] - rb['start']), '',
          '%d stretches (merged hunks) are equal-length byte ranges in which every differing 16/32-bit word changes by less' % len(tables),
          'than 0x400, i.e. only absolute addresses/offsets to moved code or resources differ (address tables, the trap',
          'dispatch table, PC-relative displacements); no instruction changes there. Ranges (%s / %s): %s.' % (
              la, lb, ', '.join('0x%06X-0x%06X / 0x%06X-0x%06X' % (span(na, h[1], h[2], ra['end']) + span(nb, h[3], h[4], rb['end']))
                                for h in tables)), '',
          'Instruction-level diff of the linear-sweep listings (difflib on mnemonics/operands with branch labels and',
          'ROM-absolute addresses normalised). %d instruction pairs differ only in a numeric operand (displacements and' % refonly,
          'references shifted by moved code/resources) and are not listed. %d substantive hunks remain:' % len(hunks), '']
    L += ['| # | %s offsets | %s offsets | lines A/B |' % (la, lb), '|---|---|---|---|']
    for n, (tag, i1, i2, j1, j2) in enumerate(hunks):
        a0 = na[i1][0] if i1 < len(na) else ra['end']
        a1 = na[i2 - 1][0] if i2 > i1 else a0
        b0 = nb[j1][0] if j1 < len(nb) else rb['end']
        b1 = nb[j2 - 1][0] if j2 > j1 else b0
        L.append('| %d | 0x%06X-0x%06X | 0x%06X-0x%06X | %d/%d |' % (n, a0, a1, b0, b1, i2 - i1, j2 - j1))
    L.append('')
    MAXL = 30
    for n, (tag, i1, i2, j1, j2) in enumerate(hunks):
        L += ['### hunk %d' % n, '', '```', '; %s' % la]
        L += [na[i][2] for i in range(max(0, i1 - 2), min(len(na), i2 + 2, i1 + MAXL))]
        if i2 - i1 > MAXL:
            L.append('; ... %d more lines' % (i2 - i1 - MAXL))
        L.append('; %s' % lb)
        L += [nb[j][2] for j in range(max(0, j1 - 2), min(len(nb), j2 + 2, j1 + MAXL))]
        if j2 - j1 > MAXL:
            L.append('; ... %d more lines' % (j2 - j1 - MAXL))
        L += ['```', '']
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('diff written: %s (%d changed regions, %d 68K hunks)' % (out, len(changed), len(hunks)))
