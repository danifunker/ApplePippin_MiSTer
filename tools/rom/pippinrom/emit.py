class Writer:
    def __init__(self, outdir, A, rom_path, rom_sha1, detok=None):
        self.out = outdir
        self.A = A
        self.d = A.d
        self.rom_path = rom_path
        self.rom_sha1 = rom_sha1
        self.detok = detok
        self.written = {}

    # ------------------------------------------------------------- helpers
    def write(self, rel, lines, header=None):
        p = os.path.join(self.out, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        mode = 'a' if rel in self.written else 'w'
        with open(p, mode) as f:
            if mode == 'a':
                f.write('\n')
            if header:
                for h in header:
                    f.write((('; ' + h) if h else ';').rstrip() + '\n')
                f.write('\n')
            for l in lines:
                f.write(l + '\n')
        self.written[rel] = True

    def common_header(self, r, extra=()):
        h = ['%s' % r['name'],
             'ROM: %s (sha1 %s)' % (os.path.basename(self.rom_path), self.rom_sha1),
             'ROM offset 0x%06X-0x%06X (%d bytes), CPU address 0x%08X (ROM base 0xFFC00000)' % (
                 r['start'], r['end'], r['end'] - r['start'], R.ROM_BASE + r['start']),
             'sha1 of these bytes: %s' % r['sha1'],
             'Generated by tools/rom (pippinrom); data only, no ROM code was executed.']
        if r.get('isa') == 'PPC':
            h.append('Notes: "rN = 0x... <name>" annotates a constant built with lis/ori/addi by its value (it may be a BAT,')
            h.append('mask or pointer, not necessarily an access); "[0x...] <name>" marks a computed load/store address.')
        return h + list(extra)

    # --------------------------------------------------------------- main
    def run(self):
        A = self.A
        if os.path.isdir(self.out):
            shutil.rmtree(self.out)
        os.makedirs(self.out)
        done_files = set()
        for r in A.regions:
            k = r['kind']
            f = r.get('file')
            if f is None:
                continue
            if r['name'].startswith('68K ROM header') or r['name'].startswith('ForeignOS'):
                if f not in done_files:
                    self.rom_header()
            elif r['name'].startswith('68K main code'):
                self.main_code(r)
            elif f == 'resources.txt':
                if f not in done_files:
                    self.resources_txt()
            elif r.get('pef') is not None:
                self.pef_region(r, f in done_files)
            elif r.get('rsrc') is not None:
                self.rsrc(r)
            elif r.get('blob'):
                self.blob(r)
            elif f == 'blob_directory.txt':
                self.blob_dir(r)
            elif f == 'configinfo.txt':
                self.configinfo(r)
            elif r.get('opcode_table'):
                self.opcode_table(r)
            elif (r.get('xcoff') is not None and k == 'header') or r.get('xcoff_sym'):
                self.xcoff(r, f in done_files)
            elif k == 'codeppc' and f.startswith('openfirmware/'):
                self.of_native(r)
            elif k == 'codeppc' and f.startswith('hwinit/'):
                self.ppc_generic(r)
            elif k == 'fcode' or r.get('fcode_desc'):
                pass   # handled together below
            elif k == 'codeppc':
                self.ppc_generic(r)
            else:
                self.write(f, hexdump(self.d, r['start'], r['end'], R.ROM_BASE + r['start']),
                           self.common_header(r))
            done_files.add(f)
        self.fcode_all()
        self.index()
        return self.written

    # ------------------------------------------------------------ 68K side
    def rom_header(self):
        A, d = self.A, self.d
        h = A.header
        c = A.cks
        L = ['68K ROM header fields (offsets per tbxi lowlevel.SuperMarioHeader):', '']
        for off, size, name in R.HEADER_FIELDS:
            v = h[name]
            L.append('  +0x%02X %-20s = 0x%0*X' % (off, name, size * 2, v))
        L += ['', 'Interpretation:',
              '  ROM version word (MachineNumber,ROMVersion) = 0x%02X%02X, ROMRelease = 0x%04X -> DingusPPC id %02X%02X%04X'
              % (h['MachineNumber'], h['ROMVersion'], h['ROMRelease'], h['MachineNumber'], h['ROMVersion'], h['ROMRelease']),
              '  RomRsrc (resource list header) at 0x%06X; RomSize 0x%X' % (h['RomRsrc'], h['RomSize']),
              '',
              'Checksums (verified by recomputation):',
              '  main  stored 0x%08X computed 0x%08X  %s  (sum of BE 16-bit words, offset 4 .. 0x%X)' % (
                  c['main_stored'], c['main_calc'], 'OK' if c['main_stored'] == c['main_calc'] else 'MISMATCH', h['RomSize']),
              ]
        for i in range(4):
            L.append('  lane%d stored 0x%08X computed 0x%08X  %s  (sum of bytes at offsets = %d mod 4, checksum fields as 0)' % (
                i, c['lanes_stored'][i], c['lanes_calc'][i], 'OK' if c['lanes_stored'][i] == c['lanes_calc'][i] else 'MISMATCH', i))
        L += ['', 'ForeignOS table at 0x50 (values are ROM offsets):']
        for n, v in h['ForeignOS']:
            L.append('  %-16s 0x%06X  (CPU 0x%08X)' % (n, v, R.ROM_BASE + v))
        L += ['', 'Header bytes:'] + hexdump(d, 0, R.FOREIGN_OS_END, R.ROM_BASE)
        L += ['', 'Jump instructions embedded in the header:']
        for off in (0x0A, 0x0E, 0x1E, 0x26, 0x2A):
            L += M68KListing(d, off, off + 4, R.ROM_BASE + off).lines()
        self.write('00_rom_header.txt', L, ['68K ROM header and ForeignOS table',
                                             'ROM: %s (sha1 %s)' % (os.path.basename(self.rom_path), self.rom_sha1)])

    def main_code_symbols(self):
        A, d = self.A, self.d
        h = A.header
        sym, cmt = {}, {}
        for off in (0x0A, 0x0E, 0x1E, 0x26, 0x2A):
            if d[off:off + 2] == b'\x4e\xfa':
                t = off + 2 + struct.unpack_from('>h', d, off + 2)[0]
                n = [x[2] for x in R.HEADER_FIELDS if x[0] == off][0]
                sym[t] = n.replace('JMP', '') + '_target'
        for n, v in h['ForeignOS']:
            if 0 < v < A.m68k_end:
                sym.setdefault(v, n)
        for n in ('EraseIconOff', 'InitSys7ToolboxOff'):
            v = h[n]
            if 0 < v < A.m68k_end:
                sym.setdefault(v, n.replace('Off', ''))
        for off, name in self.A_landmarks68k().items():
            sym.setdefault(off, name)
        return sym, cmt

    def A_landmarks68k(self):
        """Code landmarks found by byte pattern (not by address)."""
        d = self.d
        out = {}
        # Pippin logo: move.w #-20137,-(a7) ... _GetPicture
        i = d.find(b'\x3f\x3c\xb1\x57', 0, self.A.header['RomRsrc'])
        while i >= 0:
            if d.find(b'\xa9\xbc', i, i + 16) >= 0:
                out[i] = 'loads_PICT_-20137_PippinLogo'
            i = d.find(b'\x3f\x3c\xb1\x57', i + 2, self.A.header['RomRsrc'])
        i = d.find(b'\x2f\x3c' + b'rvpr', 0, self.A.header['RomRsrc'])
        while i >= 0:
            out[i] = 'push_rvpr_GetResource'
            i = d.find(b'\x2f\x3c' + b'rvpr', i + 2, self.A.header['RomRsrc'])
        return out

    def main_code(self, r):
        sym, cmt = self.main_code_symbols()
        L = M68KListing(self.d, r['start'], r['end'], R.ROM_BASE + r['start'], symbols=sym, comments=cmt).lines()
        # split by 64 KB of ROM address
        chunks = {}
        cur = r['start'] // r['split']
        for l in L:
            m = re.match(r'^[0-9A-F]{8} ([0-9A-F]{6}) ', l)
            if m:
                cur = int(m.group(1), 16) // r['split']
            chunks.setdefault(cur, []).append(l)
        files = []
        for k in sorted(chunks):
            lo = max(r['start'], k * r['split'])
            hi = min(r['end'], (k + 1) * r['split'])
            fn = 'm68k_main/%06X.s' % lo
            hdr = self.common_header(r, ['This file: ROM offsets 0x%06X-0x%06X (instructions are not split across files).' % (lo, hi),
                                         'Linear sweep: tables and strings inside the code area decode as junk instructions.',
                                         'A-line trap names: multiversal (MIT); low-memory names: multiversal LowMem defs.'])
            self.write(fn, chunks[k], hdr)
            files.append(fn)
        r['files'] = files

    def resources_txt(self):
        A, d = self.A, self.d
        h = A.rsrc_hdr
        L = ['ROM resource list header at 0x%06X: offsetToFirst 0x%X maxValidIndex %d comboFieldSize %d comboVersion %d headerSize %d' % (
            h['offset'], h['offsetToFirst'], h['maxValidIndex'], h['comboFieldSize'], h['comboVersion'], h['headerSize']), '',
            'Entries in list order (the list is singly linked from offsetToFirst; entry = combo(8) next(4) dataOff(4) type(4) id(2) attr(1) name(pstr), padded to 16).',
            'Each resource body is preceded by a 16-byte fake Memory Manager block header (\'Kurt\', 0xC0A00000, size+12, ...).', '',
            '%4s %-8s %-4s %-8s %-8s %-6s %6s %4s %-24s %-8s %s' % ('#', 'entry', 'len', 'data', 'size', 'type', 'id', 'attr', 'name', 'combo', 'next')]
        for r in A.resources:
            L.append('%4d %06X   %-4d %06X   %-8d %-6s %6d 0x%02X %-24s 0x%02X     %06X' % (
                r.index, r.entry_off, r.entry_len, r.data_off, r.size, "'%s'" % r.type_str(), r.id, r.attr,
                repr(r.name_str())[1:-1], r.combo, r.next))
        L += ['', 'Raw entry bytes:']
        for r in sorted(A.resources, key=lambda x: x.entry_off):
            L.append('%06X %s  %s' % (r.entry_off, d[r.entry_off:r.entry_off + r.entry_len].hex(), r.label()))
        self.write('resources.txt', L, ['ROM resource map', 'ROM: %s (sha1 %s)' % (os.path.basename(self.rom_path), self.rom_sha1)])

    def rsrc(self, r):
        res = r['rsrc']
        d = self.d
        body = bytes(d[res.data_off:res.data_off + res.size])
        hdr = self.common_header(r, [
            "Resource type '%s' id %d name %r attr 0x%02X combo 0x%02X" % (res.type_str(), res.id, res.name_str(), res.attr, res.combo),
            'Resource entry at 0x%06X; Memory Manager header at 0x%06X; data at 0x%06X (%d bytes, CPU 0x%08X)' % (
                res.entry_off, res.mm_off, res.data_off, res.size, R.ROM_BASE + res.data_off)])
        dec = decode(res.type, body)
        if dec:
            hdr += ['', 'Decoded header:'] + ['  ' + x for x in dec]
        if r['kind'] == 'code68k':
            L = ['; 16-byte MM header'] + hexdump(d, res.mm_off, res.data_off, R.ROM_BASE + res.mm_off) + ['']
            data_ranges = []
            if res.type == b'DRVR' and res.size > 19:
                n = d[res.data_off + 18]
                data_ranges.append((res.data_off, res.data_off + ((19 + n + 1) & ~1), 'DRVR header'))
            else:
                w = struct.unpack_from('>H', d, res.data_off)[0]
                if (w & 0xFF00) == 0x6000 and 2 < (w & 0xFF) < 0x40 and not (w & 1):
                    data_ranges.append((res.data_off + 2, res.data_off + 2 + (w & 0xFF), 'code resource header (type/id/version)'))
            hdr.append('Columns: CPU address (in-place in ROM), ROM offset, offset within resource data, bytes, instruction.')
            if res.type == b'rvpr':
                hdr.append("'rvpr' 0 is copied to the system heap and self-relocates before running (Kaisershot part 3); "
                           'the resource-relative column is what matters for it.')
            L += M68KListing(d, res.data_off, res.data_off + res.size, R.ROM_BASE + res.data_off,
                             relcol=res.data_off, data_ranges=data_ranges).lines()
            for a, b, lab in data_ranges:
                L += ['', '; %s bytes:' % lab] + hexdump(d, a, b, R.ROM_BASE + a, relbase=res.data_off)
            self.write(r['file'], L, hdr)
        else:
            hdr.append('Columns: CPU address, ROM offset, offset within resource data, hex, ASCII.')
            L = hexdump(d, res.mm_off, res.data_off + res.size, R.ROM_BASE + res.mm_off, relbase=res.data_off)
            self.write(r['file'], L, hdr)

    # ------------------------------------------------------------------ PEF
    def pef_region(self, r, already):
        res, p = r['rsrc'], r['pef']
        A = self.A
        base = rsrc_basename(res)
        d = self.d
        if r['kind'] == 'header' and not already:
            self.pef_container(r, res, p)
        elif r['kind'] == 'table':
            pass   # loader section: summarised in container.txt
        elif r['kind'] == 'codeppc':
            self.pef_code(r, res, p)
        elif r['kind'] == 'data':
            s = r['sec']
            L = ['; raw section bytes'] + hexdump(d, s['rom'], s['rom'] + s['raw_size'], R.ROM_BASE + s['rom'], relbase=s['rom'])
            un = p.unpacked.get(s['index'])
            if un is not None and s['kind'] == 2:
                L += ['', '; unpacked pattern-initialised data (%d bytes), with relocations applied symbolically:' % len(un)]
                for o in range(0, len(un), 4):
                    w = un[o:o + 4]
                    desc = p.describe_slot(s['index'], o)
                    if desc or any(w):
                        L.append('  +%06X %s%s' % (o, w.hex(), ('  -> ' + desc) if desc else ''))
            self.write(r['file'], L, self.common_header(r, ["PEF section %d kind %s, exec %d init %d raw %d" % (
                s['index'], s['kind_name'], s['exec_size'], s['init_size'], s['raw_size'])]))

    def pef_container(self, r, res, p):
        d = self.d
        L = ['Container: arch %r formatVersion %d timestamp 0x%08X oldDefVersion 0x%X oldImpVersion 0x%X currentVersion 0x%X' % (
            p.arch, p.fmt_version, p.timestamp, p.old_def_ver, p.old_imp_ver, p.cur_ver),
            'Sections (%d, %d instantiated):' % (p.nsec, p.ninst)]
        for s in p.sections:
            L.append('  #%d %-16s %-8r ROM 0x%06X (+0x%X in container) raw %6d init %6d exec %6d align 2^%d share %d' % (
                s['index'], s['kind_name'], s['name'], s['rom'], s['off'], s['raw_size'], s['init_size'], s['exec_size'], s['align'], s['share']))
        for nm, v in (('main', p.main), ('init', p.init), ('term', p.term)):
            if v:
                L.append('%s symbol: section %d offset 0x%X' % (nm, v[0], v[1]))
        L.append('')
        L.append('Imported libraries (%d):' % len(p.libs))
        for l in p.libs:
            L.append('  %-28s symbols %d..%d%s' % (l['name'], l['first'], l['first'] + l['count'] - 1, ' (weak)' if l['weak'] else ''))
        L.append('Imported symbols (%d):' % len(p.imports))
        for i, im in enumerate(p.imports):
            L.append('  [%4d] %-6s %s:%s%s' % (i, im['class'], im['lib'], im['name'], ' (weak)' if im['weak'] else ''))
        L.append('Exported symbols (%d):' % len(p.exports))
        tvs = {t[0]: t for t in p.tvectors()}
        for e in sorted(p.exports, key=lambda e: (e['section'], e['value'])):
            extra = ''
            if e['name'] in tvs:
                t = tvs[e['name']]
                extra = '  TV -> code sect%d+0x%X, TOC sect%d+0x%X' % (t[1], t[2], t[3], t[4])
            L.append('  %-6s sect %2d +0x%06X %s%s' % (e['class'], e['section'], e['value'], e['name'], extra))
        L.append('Relocated words: %d%s' % (len(p.slot), (' (reloc error: %s)' % p.reloc_error) if p.reloc_error else ''))
        L += ['', 'Container header + section name table bytes (incl. preceding 16-byte MM header):']
        L += hexdump(d, res.mm_off, min(s['rom'] for s in p.sections if s['raw_size']) if any(s['raw_size'] for s in p.sections) else p.header_end,
                     R.ROM_BASE + res.mm_off, relbase=res.data_off)
        for s in p.sections:
            if s['kind'] == 4:
                L += ['', 'Loader section bytes:'] + hexdump(d, s['rom'], s['rom'] + s['raw_size'], R.ROM_BASE + s['rom'], relbase=s['rom'])
        self.write(r['file'], L, self.common_header(r, ["Resource %s, data at 0x%06X (%d bytes)" % (res.label(), res.data_off, res.size)]))

    def pef_code(self, r, res, p):
        s = r['sec']
        d = self.d
        sym = {}
        for name, cs, cv, ts, tv in p.tvectors():
            if cs == s['index']:
                sym[s['rom'] + cv] = name
        for nm, v in (('__main', p.main), ('__init', p.init), ('__term', p.term)):
            if v:
                sec, off = v
                data = p.unpacked.get(sec)
                if data and off + 4 <= len(data):
                    slot = p.slot.get((sec, off))
                    if slot and slot[0] == 'sect' and slot[1] == s['index']:
                        sym.setdefault(s['rom'] + struct.unpack_from('>I', data, off)[0], nm)
        for e in p.exports:
            if e['section'] == s['index'] and e['class'] == 'code':
                sym.setdefault(s['rom'] + e['value'], e['name'])
        # Internal transition vectors: relocated (code ptr, data ptr) pairs in a data section.
        pairs = []
        for (sec, off), t in p.slot.items():
            if t[0] == 'sect' and t[1] == s['index']:
                t2 = p.slot.get((sec, off + 4))
                if t2 and t2[0] == 'sect' and p.sections[t2[1]]['kind'] in (1, 2):
                    pairs.append((sec, off, t[2], t2[1], t2[2]))
        for sec, off, cv, ds, dv in pairs:
            if 0 <= cv < s['raw_size']:
                sym.setdefault(s['rom'] + cv, 'tv_s%d_%X' % (sec, off))
        # TOC base: most common TOC value among exported TVs, else among internal TV pairs
        tocs = [t[4] for t in p.tvectors()]
        toc_sec = next((t[3] for t in p.tvectors()), None)
        if not tocs and pairs:
            tocs = [x[4] for x in pairs]
            toc_sec = pairs[0][3]
        toc = max(set(tocs), key=tocs.count) if tocs else None
        resolver = None
        if toc is not None and toc_sec is not None:
            resolver = lambda o, _p=p, _s=toc_sec, _t=toc: _p.describe_slot(_s, _t + o)
        # glue stubs: lwz r12,N(r2); stw r2,20(r1); lwz r0,0(r12); lwz r2,4(r12); mtctr r0; bctr
        lo, hi = s['rom'], s['rom'] + s['raw_size']
        if resolver:
            for a in range(lo, hi - 24, 4):
                w0, w1 = struct.unpack_from('>II', d, a)
                if (w0 & 0xFFFF0000) == 0x81820000 and w1 == 0x90410014:
                    t = resolver(struct.unpack_from('>h', d, a + 2)[0])
                    if t:
                        sym.setdefault(a, 'glue_' + re.sub(r'[^\w.]', '_', t.split(':')[-1]))
        hdr = self.common_header(r, [
            'Resource %s; PEF container at 0x%06X; code section #%d at container+0x%X' % (res.label(), p.base, s['index'], s['off']),
            'Columns: CPU address (code runs in place in ROM), ROM offset, offset within the code section, word, instruction.',
            'Labels: exported TVs/code symbols, traceback-table names, CFM glue stubs (by import), branch targets.',
            'TOC (r2) = data section #%s + 0x%X (most common TOC value in transition vectors)' % (toc_sec, toc) if toc is not None else 'TOC: unknown (no exported TVs)'])
        L = PPCListing(d, lo, hi, R.ROM_BASE + lo, symbols=sym, relcol=lo, toc_resolver=resolver).lines()
        self.write(r['file'], L, hdr)

    # ------------------------------------------------------------- PPC side
    def ppc_generic(self, r):
        d = self.d
        sym = dict(r.get('symbols') or {})
        cmt = {}
        extra = []
        name = r['file']
        A = self.A
        if name == 'ppc_exception_table.s':
            for o, n in PPC_VECTORS.items():
                sym[r['start'] + o] = 'vector_%04X_%s' % (o, re.sub(r'\W+', '_', n).strip('_'))
            extra.append('Runs at 0xFFF00000 + offset (MSR[IP]=1 at reset); the 603 starts at 0xFFF00100 = ROM 0x300100.')
        elif name == 'emulator.s':
            ci = A.ci
            sym[r['start'] + ci['EmulatorEntryOffset']] = 'EmulatorEntry'
            sym[r['start'] + ci['KernelTrapTableOffset']] = 'KernelTrapTable'
            extra.append('Logical address once the NanoKernel runs: LA_EmulatorCode 0x%08X (ConfigInfo).' % ci['LA_EmulatorCode'])
        elif name == 'nanokernel.s':
            extra.append('NanoKernel v01.01 (version per tbxi heuristic: "li r12,0x0101; sth r12,0xFE4(r1)").')
        elif name.startswith('hwinit/'):
            extra.append('XCOFF .text; labels from the XCOFF symbol table; .text offset = ROM offset - 0x%06X.' % r['text0'])
        L = PPCListing(d, r['start'], r['end'], r.get('vaddr', R.ROM_BASE + r['start']), symbols=sym, comments=cmt,
                       relcol=r.get('text0')).lines()
        self.write(r['file'], L, self.common_header(r, extra))

    def opcode_table(self, r):
        d = self.d
        A = self.A
        md = capstone.Cs(capstone.CS_ARCH_PPC, capstone.CS_MODE_32 | capstone.CS_MODE_BIG_ENDIAN)
        em_lo = R.ROM_BASE + A.ci['EmulatorCode_rom']
        em_hi = em_lo + A.ci['EmulatorCodeSize']
        L = []
        for i in range((r['end'] - r['start']) // 8):
            off = r['start'] + 8 * i
            a = R.ROM_BASE + off
            parts = []
            for j in range(2):
                ins = list(md.disasm_lite(bytes(d[off + 4 * j:off + 4 * j + 4]), a + 4 * j, 1))
                if not ins:
                    parts.append('.long 0x%s' % d[off + 4 * j:off + 4 * j + 4].hex())
                    continue
                mn, ops = ins[0][2], ins[0][3]
                m = re.search(r'0x[0-9a-f]+$', ops)
                if mn.startswith('b') and m:
                    t = int(m.group(0), 16)
                    if em_lo <= t < em_hi:
                        ops = ops[:m.start()] + 'emu+0x%05X' % (t - em_lo)
                parts.append(mn + ' ' + ops)
            L.append('%08X %06X op=%04X  %s %s  %-24s ; %s' % (a, off, i, d[off:off + 4].hex(), d[off + 4:off + 8].hex(), parts[0], parts[1]))
        hdr = self.common_header(r, ['One 8-byte entry per 68K opcode word (index = opcode).  Each entry is two PowerPC',
                                     'instructions executed by the emulator dispatcher; branch targets are shown relative to',
                                     'the emulator code (emu+0xNNNNN = ROM 0x%06X + N).  LA_DispatchTable = 0x%08X.' % (
                                         A.ci['EmulatorCode_rom'], A.ci['LA_DispatchTable'])])
        # split if large
        per = 32768
        if sum(len(x) for x in L) > MAX_FILE:
            files = []
            for k in range(0, len(L), per):
                fn = r['file'].replace('.s', '_%04X.s' % k)
                self.write(fn, L[k:k + per], hdr)
                files.append(fn)
            r['files'] = files
        else:
            self.write(r['file'], L, hdr)

    def blob_dir(self, r):
        lo, hi, ents = self.A.blobdir
        L = ['Directory of 16-byte entries {OSType type; UInt16 id; UInt16 0; UInt32 ROM offset; UInt32 size}.',
             'Located after the exception-table code. Which code reads it is not established here [inference: PPC-side',
             'startup / diagnostics graphics and the boot chime].', '',
             '%-8s %-4s %-6s %-8s %-8s %s' % ('entry', 'type', 'id', 'romoff', 'size', 'region')]
        for e in ents:
            L.append('%06X   %-6s 0x%02X   %06X   %-8d %s' % (e['off'], "'%s'" % e['type'].decode('latin-1'), e['id'], e['rom'], e['size'],
                                                         self.region_at(e['rom'])))
        L += [''] + hexdump(self.d, lo, hi, R.ROM_BASE + lo)
        self.write(r['file'], L, self.common_header(r))

    def region_at(self, off):
        for r in self.A.regions:
            if r['start'] <= off < r['end']:
                return r['name']
        return '?'

    def blob(self, r):
        e = r['blob']
        b = bytes(self.d[e['rom']:e['rom'] + e['size']])
        hdr = self.common_header(r, ["Blob '%s' id 0x%X from the blob directory entry at 0x%06X" % (e['type'].decode('latin-1'), e['id'], e['off'])])
        dec = decode(e['type'], b)
        if e['type'] == b'PICT' and e['size'] == 0x80:
            dec = ['128-byte blob filed as PICT; not a QuickDraw picture header (likely a raw glyph/bitmap) [inference]']
        if dec:
            hdr += ['', 'Decoded header:'] + ['  ' + x for x in dec]
        self.write(r['file'], hexdump(self.d, e['rom'], e['rom'] + e['size'], R.ROM_BASE + e['rom'], relbase=e['rom']), hdr)

    def configinfo(self, r):
        ci = self.A.ci
        L = ['ConfigInfo at ROM 0x%06X.  Component offsets in the structure are relative to this page; shown as ROM offsets.' % ci['offset'],
             'BootstrapVersion: %r' % ci['BootstrapVersion'], '']
        for o, fmt, name in R.CONFIGINFO_FIELDS:
            v = ci[name]
            s = '  +0x%03X %-24s = 0x%08X' % (o, name, v & 0xFFFFFFFF)
            comp = name[:-6] if name.endswith('Offset') else None
            if comp and comp + '_rom' in ci:
                s += '   -> ROM 0x%06X' % (ci[comp + '_rom'] & 0xFFFFFFFF)
            L.append(s)
        L += ['', 'MacLowMemInit (address = value) list:']
        for a, v in ci['LowMemInit']:
            nm = mmio_name(v)
            L.append('  [0x%04X] = 0x%08X%s' % (a, v, ('  ; ' + nm) if nm else ''))
        L += ['', 'Note: the page-mapping and BAT tables are easiest to read in tbxi\'s Configfile dump',
              '(scratch/tbxi_out/<rom>/Configfile-1), which this tool does not duplicate.', ''] + \
            hexdump(self.d, r['start'], r['end'], R.ROM_BASE + r['start'])
        self.write(r['file'], L, self.common_header(r))

    def xcoff(self, r, already):
        x = r.get('xcoff')
        d = self.d
        if x is not None and not already:
            L = ['XCOFF magic 0x%04X, %d section(s), timestamp/field 0x%08X (%r), symptr 0x%X, nsyms %d, opthdr %d, flags 0x%X' % (
                x['magic'], x['nscns'], x['timdat'], struct.pack('>I', x['timdat']), x['symptr'], x['nsyms'], x['opthdr'], x['flags'])]
            for s in x['sections']:
                L.append('  section %-8s vaddr 0x%X size 0x%X file offset 0x%X -> ROM 0x%06X-0x%06X' % (
                    s['name'], s['vaddr'], s['size'], s['scnptr'], x['offset'] + s['scnptr'], x['offset'] + s['scnptr'] + s['size']))
            if x['symbols']:
                L.append('Symbols:')
                for s in x['symbols']:
                    L.append('  %-24r value 0x%06X scnum %d sclass %d -> ROM 0x%06X' % (
                        s['name'], s['value'], s['scnum'], s['sclass'], x['offset'] + x['sections'][0]['scnptr'] + s['value']))
            L += ['', 'Header bytes:'] + hexdump(d, r['start'], r['end'], R.ROM_BASE + r['start'])
            self.write(r['file'], L, self.common_header(r))
        elif r.get('xcoff_sym'):
            L = ['XCOFF symbol table + string table bytes:'] + hexdump(d, r['start'], r['end'], R.ROM_BASE + r['start'])
            if r.get('clipped_from'):
                L.append('NOTE: the string table would run to 0x%06X but the next region (a directory blob) starts at 0x%06X;'
                         ' the last string is overwritten in this ROM.' % (r['clipped_from'], r['end']))
            self.write(r['file'], L, self.common_header(r))

    # ------------------------------------------------------- Open Firmware
    def of_native(self, r):
        A, d = self.A, self.d
        sym, data = {}, []
        words = A.of_headers
        for w in words:
            sym[w['code']] = w['name'] or 'headerless_tok_%03X' % w['token']
            data.append((w['hdr'], w['code'], 'Forth header: %s token 0x%03X flags 0x%02X, type 0x%02X %s' % (
                repr(w['name']) if w['name'] else '(headerless)', w['token'], w['flags'], w['b5'], DEFINERS.get(w['b5'], ''))))
        t0 = r['text0']
        L = PPCListing(d, r['start'], r['end'], R.ROM_BASE + r['start'], symbols=sym, data_ranges=data, relcol=t0,
                       tbtables=False).lines()
        hdr = self.common_header(r, [
            'XCOFF .text starts at ROM 0x%06X; third column is the .text offset.' % t0,
            'ConfigInfo: LA_OpenFirmware 0x%08X, PA_OpenFirmware 0x%08X [inference: the image is copied to RAM and run there,'
            % (A.ci['LA_OpenFirmware'], A.ci['PA_OpenFirmware']),
            'which matches the FF8xxxxx node addresses in Kaisershot part 5].',
            'Forth word headers (link, flags, type, token, name) are shown as .long data; %d words, %d named.' % (
                len(words), sum(1 for w in words if w['name'])),
            'The type byte matches FCode definer tokens (0xB7 b(:), 0xB8 b(value), 0xBA b(constant), ...) [inference].'])
        self.write(r['file'], L, hdr)
        W = ['%-8s %-8s %-6s %-5s %-4s %-12s %s' % ('header', 'code', 'token', 'flags', 'type', 'definer', 'name')]
        for w in words:
            W.append('%06X   %06X   0x%03X  0x%02X  0x%02X %-12s %s' % (w['hdr'], w['code'], w['token'], w['flags'], w['b5'],
                                                                DEFINERS.get(w['b5'], '?'), w['name'] or '(headerless)'))
        self.write('openfirmware/of_words.txt', W, ['Open Firmware native Forth words (ROM offsets)',
                                                     'ROM: %s' % os.path.basename(self.rom_path)])

    def fcode_all(self):
        A, d = self.A, self.d
        if not getattr(A, 'fcode', None):
            return
        tmp = tempfile.mkdtemp(prefix='pippin_fcode_')
        try:
            vlist = os.path.join(tmp, 'vendor.txt')
            seen = set()
            with open(vlist, 'w') as f:
                for w in A.of_headers:
                    if w['name'] and 0x10 <= w['token'] < 0x800 and w['token'] not in seen:
                        f.write('0x%03X %s\n' % (w['token'], w['name']))
                        seen.add(w['token'])
            descs = {r['end']: r for r in A.regions if r.get('fcode_desc')}
            for r in A.regions:
                if r['kind'] != 'fcode':
                    continue
                f = r['fcode']
                o = f['off']
                bin_ = os.path.join(tmp, 'img%02d.bin' % r['index'])
                with open(bin_, 'wb') as fh:
                    fh.write(d[o:o + f['len']])
                hdr = self.common_header(r, ['FCode image %d: version1 header, checksum 0x%04X (verified), length %d.' % (r['index'], f['checksum'], f['len'])])
                if o in descs:
                    dr = descs[o]
                    link, dev, ven, cls, z = struct.unpack_from('>iHHII', d, dr['start'])
                    hdr += ['Descriptor at 0x%06X: link %+d (-> 0x%06X), u16 0x%04X, u16 0x%04X, u32 0x%08X, u32 0x%X' % (
                        dr['start'], link, dr['start'] + link, dev, ven, cls, z),
                        '[inference] 0x106B = Apple PCI vendor id, so (device,vendor) or a PCI class code (0x060400 = PCI-PCI bridge)',
                        'selects which node the image is evaluated for.']
                if self.detok and os.path.exists(self.detok):
                    res = subprocess.run([self.detok, '-o', '-f', vlist, bin_], capture_output=True, text=True)
                    out = [x for x in (res.stdout + res.stderr).splitlines()
                           if 'Reading additional FCodes' not in x and 'is already defined as' not in x]
                    hdr += ['Detokenised with OpenBIOS fcode-utils detok (-o: offsets are relative to the image start;',
                            'add 0x%06X for the ROM offset). Native kernel words were supplied as vendor FCodes from' % o,
                            'the Forth headers (openfirmware/of_words.txt).']
                    self.write(r['file'], ['\\ ' + x if not x.startswith('\\') and False else x for x in out], hdr)
                else:
                    hdr.append('detok not available: hex dump only.')
                    self.write(r['file'], hexdump(d, o, o + f['len'], R.ROM_BASE + o, relbase=o), hdr)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    # --------------------------------------------------------------- index
    def index(self):
        A = self.A
        h = A.header
        cov = A.coverage()
        total = R.ROM_SIZE
        L = ['# %s: ROM region map' % A.label, '',
             '- ROM file: `%s`' % os.path.basename(self.rom_path),
             '- SHA-1: `%s`, size %d bytes, CPU base 0xFFC00000' % (self.rom_sha1, total),
             '- 68K ROM header checksum 0x%08X (%s); ROM version 0x%02X%02X, release 0x%04X' % (
                 A.cks['main_stored'], 'verified' if A.cks['main_stored'] == A.cks['main_calc'] else 'MISMATCH',
                 h['MachineNumber'], h['ROMVersion'], h['ROMRelease']),
             '- Generated by `tools/rom/disassemble.sh`; every byte is in exactly one row below (rows are contiguous).',
             '']
        from .landmarks import check
        L += ['## Landmark checks', '', '| status | check | detail |', '|---|---|---|']
        for n, st, dt in check(A, self.rom_path):
            L.append('| %s | %s | %s |' % (st, n.replace('|', '/'), dt.replace('|', '/')))
        L += ['', '## Coverage', '', '| kind | bytes | % of ROM |', '|---|---:|---:|']
        for k in sorted(cov, key=lambda k: -cov[k]):
            L.append('| %s | %d | %.3f |' % (k, cov[k], 100.0 * cov[k] / total))
        ident = total - cov.get('unknown', 0)
        L += ['| **identified (all but unknown)** | %d | %.3f |' % (ident, 100.0 * ident / total), '']
        if A.notes:
            L += ['Notes:', ''] + ['- ' + n for n in A.notes] + ['']
        groups = []
        for r in A.regions:
            if r['group'] not in groups:
                groups.append(r['group'])
        for g in groups:
            rows = [r for r in A.regions if r['group'] == g]
            L += ['## %s (%d regions)' % (g, len(rows)), '', '| ROM offset | end | size | kind | ISA | region | file | sha1 (8) |', '|---|---|---:|---|---|---|---|---|']
            for r in rows:
                files = r.get('files') or ([r['file']] if r.get('file') else [])
                fl = ', '.join('[%s](%s)' % (f, f) for f in files[:3]) + (' (+%d more)' % (len(files) - 3) if len(files) > 3 else '')
                L.append('| 0x%06X | 0x%06X | %d | %s | %s | %s | %s | %s |' % (
                    r['start'], r['end'], r['end'] - r['start'], r['kind'], r['isa'], r['name'].replace('|', '/'), fl, r['sha1'][:8]))
            L.append('')
        with open(os.path.join(self.out, 'index.md'), 'w') as f:
            f.write('\n'.join(L) + '\n')
